# Operadores de comparación

v1 = float(input("Oe pa, ingresa pues el valor uno ok?: "))
v2 = float(input("Oe pa, ingresa pues el valor dos ok?: "))

if(v1 == v2):
    print(str(v1) + " es igual a "+ str(v2) + " : SÍ.");

else:
    print(str(v1) + " es igual a "+ str(v2) + " : NO.");

if(v1 != v2):
    print(str(v1) + " es distinto a "+ str(v2) + " : SÍ.");

else:
    print(str(v1) + " es distinto a "+ str(v2) + " : No.");

if(v1 > v2):
    print(str(v1) + " es mayor a "+ str(v2) + " : Sí.");

else:
    print(str(v1) + " es mayor a "+ str(v2) + " : No.");

if(v1 < v2):
    print(str(v1) + " es menor a "+ str(v2) + " : Sí.");

else:
    print(str(v1) + " es menor a "+ str(v2) + " : No.");

if(v1 >= v2):
    print(str(v1) + " es mayor o igual a "+ str(v2) + " : Sí.");

else:
     print(str(v1) + " es mayor o igual a "+ str(v2) + " : No.");

if(v1 <= v2):
     print(str(v1) + " es menor o igual a "+ str(v2) + " : Sí.");

else:
     print(str(v1) + " es menor o igual a "+ str(v2) + " : No.");

